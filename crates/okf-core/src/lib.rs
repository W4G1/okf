/// The OKF specification version this crate implements.
pub const OKF_VERSION: &str = "0.3";

/// Specification versions this crate can consume.
///
/// Each version's breaking changes come with a consumer fallback, and this
/// crate applies them, so a bundle written for an earlier version loads and
/// validates without special handling: v0.1's `timestamp` and `# Citations`,
/// and v0.2's root-relative path fields. See
/// [`legacy_fallbacks_apply`].
pub const SUPPORTED_OKF_VERSIONS: [&str; 3] = ["0.1", "0.2", "0.3"];

