//! # okf-core: the Open Knowledge Format, in pure Rust
//!
//! A pure-Rust implementation of the [Open Knowledge Format (OKF)
//! v0.3][spec], an open, human- and agent-friendly format for
//! representing knowledge as a directory of markdown files with YAML
//! frontmatter.
//!
//! OKF is intentionally minimal ("if you can `cat` a file, you can read OKF; if
//! you can `git clone` a repository, you can ship it"), so this crate implements it
//! with the standard library alone: its own [YAML-subset parser](yaml), a
//! markdown [link scanner](links), and a directory walker. The companion `okf` crate re-exports this
//! entire library and ships the `okf` command-line tool.
//!
//! ## Model
//!
//! - A [`Bundle`] is a directory tree of markdown files.
//! - A [`Concept`] is one markdown [`Document`] = YAML [`Frontmatter`] + body,
//!   whose frontmatter has a non-empty `type`. A markdown file without one is
//!   not a concept, and is skipped.
//! - A [`ConceptId`] is a concept's path within the bundle, minus `.md`.
//! - Concepts relate via markdown [`links`] and path fields; the bundle
//!   exposes the resulting graph and backlinks.
//! - `index.md` directory listings are generated by [`index`], and the
//!   bundle-root one carries the [`BundleMetadata`].
//! - `log.md` histories are parsed by [`log`].
//! - Conformance checking and linting live in the companion
//!   [`okf-validator`](https://docs.rs/okf-validator) crate.
//!
//! ## The frontmatter families
//!
//! Provenance, trust, freshness, lifecycle, and attestation are first-class.
//! Every one of these keys is optional, and absence is meaningful rather than
//! invalid.
//!
//! | Concern     | Frontmatter                                                    | Module          |
//! |-------------|----------------------------------------------------------------|-----------------|
//! | Provenance  | `sources`, `usage_window`                                      | [`provenance`]  |
//! | Trust       | `generated`, `verified`, trust tiers                           | [`trust`]       |
//! | Lifecycle   | `status`, `superseded_by`, `stale_after`                       | [`trust`]       |
//! | Identity    | the actor convention                                           | [`actor`]       |
//! | Attestation | `runtime`, `parameters`, `computation`, `executor`, `attester` | [`computation`] |
//! | Attribution | `[^label]` footnotes keyed to `sources[].id`                   | [`footnotes`]   |
//!
//! ## What v0.3 changes
//!
//! v0.3 makes the v0.2 text precise and has two breaking changes in how a
//! consumer reads an existing value. Both are implemented here:
//!
//! - **Path fields resolve like links.** A path field without a leading `/`
//!   resolves from the directory of its file, not from the bundle root. For a
//!   bundle that declares `okf_version` 0.2 or earlier, or no version, the
//!   root reading remains available as a fallback; see
//!   [`Bundle::resolve_path`] and [`PathResolution::Fallback`].
//! - **Only current verifications give the trust tier.** A `verified` event
//!   counts only when its `at` is at or after `generated.at`; see
//!   [`TrustTier::derive`]. The tier can only go down, which is the safe
//!   direction.
//!
//! It also adds `superseded_by` for deprecated concepts, bundle metadata in
//! the bundle-root `index.md`, and rules for extension keys; accepts a
//! date-only timestamp as the start of that day in UTC; and tells a consumer
//! what to do with values that are absent, empty, or oddly shaped. The
//! accessors on [`Frontmatter`] apply those rules.
//!
//! Two v0.1 constructs are superseded but still readable: `timestamp` gives
//! way to `generated.at` (see [`Frontmatter::content_changed_at`]), and the
//! body `# Citations` list gives way to `sources` (see
//! [`Document::citations`]).
//!
//! ## Example
//!
//! ```no_run
//! use okf_core::{Bundle, ConceptId};
//!
//! let bundle = Bundle::load("./my_bundle")?;
//! println!("{} concepts", bundle.len());
//!
//! let id = ConceptId::parse("tables/orders")?;
//! for link in bundle.links_from(&id) {
//!     println!("{} -> {} (exists: {})", id, link.target, link.exists);
//! }
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! Reading a concept's trust signals:
//!
//! ```
//! use okf_core::{Document, TrustTier};
//!
//! let doc = Document::parse(
//!     "---\n\
//!      type: Metric\n\
//!      title: Revenue\n\
//!      status: stable\n\
//!      generated: { by: reference_agent/gemini-2.5-pro, at: \"2026-06-20T22:53:05Z\" }\n\
//!      verified: { by: \"human:walter\", at: \"2026-06-25T09:00:00Z\" }\n\
//!      stale_after: \"2026-12-31\"\n\
//!      ---\n\n\
//!      # Definition\n",
//! )
//! .unwrap();
//!
//! // A bare `verified` mapping counts as a one-element list.
//! assert_eq!(doc.frontmatter.verified().len(), 1);
//! // The review is after the last change, so it is current.
//! assert_eq!(doc.frontmatter.trust_tier(), TrustTier::HumanReviewed);
//! assert_eq!(doc.frontmatter.status().to_string(), "stable");
//! ```
//!
//! [spec]: https://github.com/open-knowledge-format/open-knowledge-format/blob/main/SPEC.md

