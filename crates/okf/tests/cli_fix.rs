#[test]
fn cli_validate_with_fix_normalizes_date_formats() {
    let tmp = TempDir::new();
    tmp.write(
        "index.md",
        "---\nokf_version: \"0.3\"\n---\n\n# Test\n\n* [Revenue](metrics/revenue.md)\n",
    );
    tmp.write(
        "metrics/revenue.md",
        "---\ntype: Metric\ntitle: Revenue\ndescription: Revenue tracking.\ngenerated:\n  by: human:alice\n  at: '2026-06-30'\nverified:\n  - by: human:bob\n    at: '2026-07-01 12:00:00'\nstale_after: '2026-12-31'\nusage_window:\n  from: '2026-01-01'\n  to: '2026-06-01'\nsources:\n  - id: '1'\n    resource: https://example.com\n    last_modified: '2026-05-15'\n---\n\n# Revenue\n\nRevenue is money.\n",
    );

    let val_before = okf()
        .args(["validate", tmp.path().to_str().unwrap(), "--json"])
        .output()
        .unwrap();
    let val_json_before: serde_json::Value = serde_json::from_slice(&val_before.stdout).unwrap();
    assert!(
        val_json_before["diagnostics"]
            .as_array()
            .unwrap()
            .iter()
            .any(|d| d["fixable"].as_bool() == Some(true)),
        "Expected fixable date diagnostics"
    );

    let fix_output = okf()
        .args(["validate", tmp.path().to_str().unwrap(), "--fix", "--json"])
        .output()
        .unwrap();
    assert!(fix_output.status.success());

    let val_after = okf()
        .args(["validate", tmp.path().to_str().unwrap(), "--json"])
        .output()
        .unwrap();
    let val_json_after: serde_json::Value = serde_json::from_slice(&val_after.stdout).unwrap();
    assert_eq!(
        val_json_after["error_count"].as_i64(),
        Some(0),
        "Expected 0 errors after fix"
    );
    assert_eq!(
        val_json_after["warning_count"].as_i64(),
        Some(0),
        "Expected 0 warnings after fix"
    );
    assert_eq!(
        val_json_after["conformant"].as_bool(),
        Some(true),
        "Expected conformant after fix"
    );

    let content = tmp.read("metrics/revenue.md");
    // The two timestamps consumers compare become date-times, and a
    // date-time without an offset gains one.
    assert!(
        content.contains("at: \"2026-06-30T00:00:00Z\""),
        "{content}"
    );
    assert!(
        content.contains("at: \"2026-07-01T12:00:00Z\""),
        "{content}"
    );
    // A date-only value is valid everywhere else, so it is left exactly as
    // written, quotes included.
    assert!(content.contains("stale_after: '2026-12-31'\n"), "{content}");
    assert!(content.contains("  from: '2026-01-01'\n"), "{content}");
    assert!(content.contains("  to: '2026-06-01'\n"), "{content}");
    assert!(
        content.contains("    last_modified: '2026-05-15'\n"),
        "{content}"
    );
}

#[test]
fn cli_validate_with_fix_migrates_a_v0_2_bundle() {
    // A bundle written to OKF v0.2: path fields from the bundle root without a
    // leading `/`, a scalar `tags`, an indented computation, frontmatter in
    // log.md, and no declared version.
    let tmp = TempDir::new();
    tmp.write(
        "index.md",
        "# Computations\n\n* [Revenue](computations/revenue.md) - Revenue.\n",
    );
    tmp.write(
        "log.md",
        "---\ntype: Log\n---\n\n# History\n\n## 2026-06-30\n\n- **Created** the bundle.\n",
    );
    tmp.write(
        "references/skills/run-on-bq.md",
        "# Run on BigQuery\n\nSteps.\n",
    );
    tmp.write("references/attesters/sql-equality.py", "print('ok')\n");
    let revenue = "---\n\
        type: Attested Computation\n\
        title: Revenue\n\
        description: Recognized revenue.\n\
        tags: finance, revenue\n\
        runtime: bigquery\n\
        executor:\n\
        \x20 resource: references/skills/run-on-bq.md   # from the bundle root\n\
        \x20 receipt: [job_id, executed_sql]\n\
        attester: { resource: references/attesters/sql-equality.py, x-acme-timeout: 30 }\n\
        generated: { by: reference_agent/gemini-2.5-pro, at: 2026-06-20T14:00:00Z }\n\
        verified: { by: human:ahormati, at: 2026-06-25T09:00:00Z }\n\
        x-acme-owner: finance   # kept as written\n\
        ---\n\n\
        # Revenue\n\n\
        ## Computation\n\n\
        \x20   SELECT SUM(amount) AS revenue\n\
        \x20   FROM finance.recognized_revenue\n\n\
        Prose after the block.\n";
    tmp.write("computations/revenue.md", revenue);
    let root = tmp.path().to_str().unwrap();

    let before: serde_json::Value = serde_json::from_slice(
        &okf()
            .args(["validate", root, "--json"])
            .output()
            .unwrap()
            .stdout,
    )
    .unwrap();
    // The log frontmatter is the one conformance error; the rest still reads
    // through the fallbacks for bundles from earlier versions.
    assert_eq!(before["conformant"].as_bool(), Some(false));
    assert_eq!(before["error_count"].as_i64(), Some(1), "{before:#?}");

    let fix = okf().args(["validate", root, "--fix"]).output().unwrap();
    assert!(
        fix.status.success(),
        "{}",
        String::from_utf8_lossy(&fix.stdout)
    );

    let fixed = tmp.read("computations/revenue.md");
    // Path fields gain their leading `/`, and nothing else on those entries
    // changes that does not have to.
    assert!(
        fixed.contains("  resource: /references/skills/run-on-bq.md\n"),
        "{fixed}"
    );
    assert!(
        fixed.contains("  resource: /references/attesters/sql-equality.py\n"),
        "{fixed}"
    );
    assert!(fixed.contains("  x-acme-timeout: 30\n"), "{fixed}");
    // The scalar tags become a list, and the indented block is fenced.
    assert!(
        fixed.contains("tags:\n  - finance\n  - revenue\n"),
        "{fixed}"
    );
    assert!(
        fixed.contains("## Computation\n\n```bigquery\nSELECT SUM(amount) AS revenue\nFROM finance.recognized_revenue\n```\n\nProse after the block.\n"),
        "{fixed}"
    );
    // Entries that needed no fix are byte for byte what the author wrote.
    assert!(
        fixed.contains(
            "generated: { by: reference_agent/gemini-2.5-pro, at: 2026-06-20T14:00:00Z }\n"
        )
    );
    assert!(fixed.contains("verified: { by: human:ahormati, at: 2026-06-25T09:00:00Z }\n"));
    assert!(fixed.contains("x-acme-owner: finance   # kept as written\n"));

    // The log loses its frontmatter and nothing else.
    assert_eq!(
        tmp.read("log.md"),
        "# History\n\n## 2026-06-30\n\n- **Created** the bundle.\n"
    );
    // With no path depending on the root fallback any more, the version is
    // declared.
    assert!(
        tmp.read("index.md")
            .starts_with("---\nokf_version: \"0.3\"\n---\n\n# Computations\n")
    );

    let after: serde_json::Value = serde_json::from_slice(
        &okf()
            .args(["validate", root, "--json"])
            .output()
            .unwrap()
            .stdout,
    )
    .unwrap();
    assert_eq!(after["conformant"].as_bool(), Some(true), "{after:#?}");
    assert_eq!(after["error_count"].as_i64(), Some(0));
    // What remains is the run instructions file, which is not a concept.
    let warnings: Vec<&str> = after["diagnostics"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|d| d["severity"] == "warning")
        .map(|d| d["message"].as_str().unwrap())
        .collect();
    assert_eq!(warnings.len(), 1, "{warnings:#?}");
    assert!(warnings[0].contains("not a concept"));

    // Fixing again changes nothing.
    let snapshot = (
        tmp.read("computations/revenue.md"),
        tmp.read("index.md"),
        tmp.read("log.md"),
    );
    okf().args(["validate", root, "--fix"]).output().unwrap();
    assert_eq!(
        snapshot,
        (
            tmp.read("computations/revenue.md"),
            tmp.read("index.md"),
            tmp.read("log.md")
        )
    );
}
